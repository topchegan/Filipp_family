// Силуэт: та же картинка, но залитая одним цветом (для титульного экрана)
function makeSilhouette(frame, color) {
  const c = document.createElement('canvas');
  c.width = frame.width;
  c.height = frame.height;
  const g = c.getContext('2d');
  g.drawImage(frame, 0, 0);
  g.globalCompositeOperation = 'source-in'; // красим только непрозрачные пиксели
  g.fillStyle = color;
  g.fillRect(0, 0, c.width, c.height);
  return c;
}

// Рисует кадр в точке x, y. flip = true — отразить по горизонтали (смотрит влево).
function drawSprite(ctx, frame, x, y, flip) {
  if (!flip) {
    ctx.drawImage(frame, x, y);
    return;
  }
  ctx.save();
  ctx.translate(x + frame.width, y); // сдвигаемся к правому краю картинки
  ctx.scale(-1, 1);                  // и отражаем
  ctx.drawImage(frame, 0, 0);
  ctx.restore();
}
