// Где сейчас сиденье качелей (x, y — левый верхний угол качелей, t — время)
function swingSeat(x, y, t) {
  const angle = 0.9 * Math.sin(t / 22);             // раскачивается туда-сюда
  const len = 22;                                   // длина верёвки
  const cx = x + 20 + Math.round(Math.sin(angle) * len);
  const cy = y + 4 + Math.round(Math.cos(angle) * len);
  return { x: cx - 8, y: cy - 1, w: 16, h: 4, swingDir: Math.cos(t / 22) >= 0 ? 1 : -1 };
}

