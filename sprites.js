// Сердечко от мамы (розовое: малиновый и коралловый из палитры). big — большое «ФОТО ИЗ ДЕТСТВА» 14x12
function drawLoveHeart(g, x, y, big) {
  const map = big ? [
    '..000...000...',
    '.03330.03330..',
    '0333c303333.0.',
    '03c33333333320',
    '03333333333320',
    '03333333333220',
    '.033333333220.',
    '..0333333220..',
    '...03333220...',
    '....033220....',
    '.....0320.....',
    '......00......',
  ] : [
    '.00.00.',
    '03c0320',
    '0333320',
    '0333220',
    '.03220.',
    '..020..',
    '...0...',
  ];
  const colors = { '0': '#5d275d', '2': '#b13e53', '3': '#ef7d57', 'c': '#f4f4f4' };
  map.forEach((row, j) => {
    for (let i = 0; i < row.length; i++) {
      const c = colors[row[i]];
      if (!c) continue;
      g.fillStyle = c;
      g.fillRect(x + i, y + j, 1, 1);
    }
  });
  if (big) {                                          // фото в рамке на сердце
    g.fillStyle = '#f4f4f4';
    g.fillRect(x + 4, y + 3, 6, 5);
    g.fillStyle = '#ffcd75';
    g.fillRect(x + 6, y + 4, 2, 2);
    g.fillStyle = '#41a6f6';
    g.fillRect(x + 5, y + 6, 4, 1);
  }
}

// Серое облачко-просьба 14x11 со значком: tap — кран, toilet — унитаз, bulb — лампочка, tile — плитка
function drawRequest(g, x, y, kind) {
  g.fillStyle = '#333c57';
  g.fillRect(x + 1, y + 1, 12, 9);
  g.fillRect(x, y + 3, 14, 5);
  g.fillRect(x + 3, y, 8, 11);
  g.fillStyle = '#94b0c2';
  g.fillRect(x + 2, y + 2, 10, 7);
  g.fillRect(x + 1, y + 4, 12, 3);
  g.fillRect(x + 4, y + 1, 6, 9);
  const ix = x + 4, iy = y + 2;                       // значок 6x6
  if (kind === 'tap') {
    g.fillStyle = '#566c86';
    g.fillRect(ix, iy + 1, 5, 2);                      // кран
    g.fillRect(ix + 4, iy + 1, 2, 3);
    g.fillRect(ix + 1, iy, 2, 1);
    g.fillStyle = '#3b5dc9';
    g.fillRect(ix + 4, iy + 5, 2, 1);                  // капля
  } else if (kind === 'toilet') {
    g.fillStyle = '#f4f4f4';
    g.fillRect(ix, iy, 3, 3);                          // бачок
    g.fillRect(ix, iy + 3, 6, 2);                      // унитаз
    g.fillRect(ix + 2, iy + 5, 3, 1);
    g.fillStyle = '#566c86';
    g.fillRect(ix + 1, iy + 3, 4, 1);
  } else if (kind === 'bulb') {
    g.fillStyle = '#ffcd75';
    g.fillRect(ix + 1, iy, 4, 3);                      // лампочка
    g.fillRect(ix + 2, iy + 3, 2, 1);
    g.fillStyle = '#566c86';
    g.fillRect(ix + 2, iy + 4, 2, 2);                  // цоколь
  } else {
    g.fillStyle = '#41a6f6';                           // плитка
    g.fillRect(ix, iy, 6, 6);
    g.fillStyle = '#29366f';
    g.fillRect(ix + 3, iy, 1, 6);
    g.fillRect(ix, iy + 3, 6, 1);
    g.fillRect(ix + 4, iy + 1, 1, 1);                  // трещина
  }
}

