// Рисует одну плитку # в стиле фона. topOpen = сверху пусто (рисуем верхний край)
function drawSolidTile(g, x, y, style, topOpen, row) {
  g.fillStyle = style.fill;
  g.fillRect(x, y, 8, 8);
  g.fillStyle = style.seam;
  g.fillRect(x, y + 7, 8, 1);                       // горизонтальный шов
  g.fillRect(x + (row % 2 ? 0 : 4), y, 1, 7);       // вертикальный шов «кирпичиком»
  if (topOpen) {
    g.fillStyle = style.top;
    g.fillRect(x, y, 8, 2);
  }
}

// Рисует тонкую платформу «-» (полку) в стиле фона
function drawShelfTile(g, x, y, colors) {
  g.fillStyle = colors[0];
  g.fillRect(x, y, 8, 3);
  g.fillStyle = colors[1];
  g.fillRect(x, y + 3, 8, 1);
}

// Силуэт: та же картинка, но залитая одним цветом (для титульного экрана)
function makeSilhouette(frame, color) {
  const c = document.createElement('canvas');
  c.width = frame.width;
  c.height = frame.height;
  const g = c.getContext('2d');
  g.drawImage(frame, 0, 0);
  g.globalCompositeOperation = 'source-in'; // красим только непрозрачные пиксели
  g.fillStyle = color;
  g.fillRect(0, 0, c.width, c.height);
  return c;
}

// Рисует кадр в точке x, y. flip = true — отразить по горизонтали (смотрит влево).
function drawSprite(ctx, frame, x, y, flip) {
  if (!flip) {
    ctx.drawImage(frame, x, y);
    return;
  }
  ctx.save();
  ctx.translate(x + frame.width, y); // сдвигаемся к правому краю картинки
  ctx.scale(-1, 1);                  // и отражаем
  ctx.drawImage(frame, 0, 0);
  ctx.restore();
}
