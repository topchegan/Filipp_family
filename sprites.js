// =============================================
// Превращаем пиксельные карты в картинки
// =============================================

// Рисует одну пиксельную карту на маленьком холсте.
// Делаем это один раз при запуске, а потом просто копируем готовую картинку.
function makeFrame(rows, w, h, label) {
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  const g = c.getContext('2d');
  if (rows.length !== h) console.warn(label + ': рядов ' + rows.length + ', а нужно ' + h);
  rows.forEach((row, y) => {
    if (row.length !== w) console.warn(label + ', ряд ' + y + ': длина ' + row.length + ', а нужно ' + w);
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '.') continue;            // прозрачный пиксель
      const color = PALETTE[ch];
      if (!color) { console.warn(label + ': неизвестный символ «' + ch + '»'); continue; }
      g.fillStyle = color;
      g.fillRect(x, y, 1, 1);
    }
  });
  return c;
}

// Готовим все анимации персонажа
function buildCharacter(name, w, h, anims) {
  const result = { name: name, w: w, h: h, anims: {} };
  for (const key in anims) {
    const a = anims[key];
    result.anims[key] = {
      name: a.name,
      speed: a.speed,
      frames: a.frames.map((rows, i) => makeFrame(rows, w, h, name + ' ' + key + ' #' + i)),
    };
  }
  return result;
}

