// Ширина текста в пикселях (одной строкой)
function textWidth(text) {
  return text.length === 0 ? 0 : text.length * CHAR_STEP - 1;
}

// Рисует одну букву. scale — во сколько раз увеличить (1 — обычный размер).
function drawChar(ctx, ch, x, y, scale) {
  let glyph = GLYPHS[ch];
  if (!glyph) glyph = GLYPHS['?'];   // неизвестный символ рисуем как «?»
  const rows = glyph.split(' ');
  for (let ry = 0; ry < FONT_H; ry++) {
    for (let rx = 0; rx < FONT_W; rx++) {
      if (rows[ry][rx] === '#') {
        ctx.fillRect(x + rx * scale, y + ry * scale, scale, scale);
      }
    }
  }
}

// Делит текст на строки, чтобы каждая влезала в ширину maxWidth.
// Слова не разрываются. Знак «\n» в тексте — принудительный перенос.
function wrapText(text, maxWidth) {
  const maxChars = Math.max(1, Math.floor((maxWidth + 1) / CHAR_STEP));
  const lines = [];
  for (const paragraph of String(text).toUpperCase().split('\n')) {
    let line = '';
    for (const word of paragraph.split(' ')) {
      if (line === '') line = word;
      else if ((line + ' ' + word).length <= maxChars) line += ' ' + word;
      else { lines.push(line); line = word; }
    }
    lines.push(line);
  }
  return lines;
}

// Рисует текст.
//   color    — цвет из палитры, например '#f4f4f4'
//   maxWidth — ширина, по которой переносить строки (если не задана — без переноса)
//   options.scale    — увеличение (по умолчанию 1)
//   options.maxChars — сколько букв показать (для текста «по буквам»)
// Возвращает число строк.
function drawText(ctx, text, x, y, color, maxWidth, options) {
  const opt = options || {};
  const scale = opt.scale || 1;
  const lines = maxWidth ? wrapText(text, maxWidth / scale) : String(text).toUpperCase().split('\n');
  let left = opt.maxChars === undefined ? Infinity : opt.maxChars;
  ctx.fillStyle = color;
  lines.forEach((line, i) => {
    for (let c = 0; c < line.length && left > 0; c++, left--) {
      drawChar(ctx, line[c], x + c * CHAR_STEP * scale, y + i * LINE_STEP * scale, scale);
    }
  });
  return lines.length;
}

// Рисует текст по центру относительно точки centerX (одной строкой)
function drawTextCentered(ctx, text, centerX, y, color, scale) {
  const s = scale || 1;
  const x = Math.round(centerX - (textWidth(String(text)) * s) / 2);
  drawText(ctx, text, x, y, color, 0, { scale: s });
}
