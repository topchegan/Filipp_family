// =============================================
// КАРТЫ УРОВНЕЙ
// =============================================
//
// Мир состоит из плиток 8x8 пикселей. Один экран — 30 плиток в ширину и 15 в высоту
// (ещё 2 ряда сверху занимает HUD).
//
// Уровень делится на ЧАСТИ (parts). Каждая часть — свой список ЭКРАНОВ (screens),
// они идут друг за другом слева направо. Между частями — затемнение и титр с названием части.
// Шкала HUD, Лера и часы считают весь уровень целиком, через все части.
//
// Каждая часть:
//   name      — название (для титра «ЧАСТЬ 2. ВТОРОЙ ЭТАЖ»)
//   exitScene — (не обязательно) сценка из scenes.js при выходе из части
//   screens   — список экранов
//
// Каждый экран:
//   bg  — фон экрана (обои, окна и мелкие вещи; от него же зависит вид плиток #)
//   map — ровно 15 строк, в каждой ровно 30 символов
//
// Подробная инструкция для правки на iPad — в docs/levels.md.
//
// ЛЕГЕНДА СИМВОЛОВ:
//   .  пусто
//   #  твёрдая плитка (пол, стена). Как она выглядит — зависит от фона экрана
//   -  полка: на неё можно запрыгнуть снизу насквозь, а стоять сверху
//   P  старт Филиппа (ровно один в КАЖДОЙ части)
//   C  телефон: коснулся — звонок-отмазка Лере, Лера отлетает назад. После звонка телефон исчезает
//   N  выход в следующую часть, 3x4 (ровно один в каждой части, кроме последней).
//      Обычно проход на лестнице наверх; на фоне windowEnd рисуется как открытое окно
//   E  финиш — калитка «ВЫХОД», 4x4 (ровно один, только в последней части)
//   L  Лера с досками, 2x3 — просто картинка, не враг и не препятствие.
//      Когда Филипп доходит до лестницы левее неё, она говорит «Я ТЕБЯ ЖДУ!»
//
// ПРЕДМЕТЫ. Все твёрдые: сквозь них не пройти, сверху можно стоять.
// Размер — ширина x высота в плитках.
//   D  диван, 5x2
//   T  стол со скатертью, 4x2 (под ним не пройти)
//   W  шкаф, 4x4
//   F  холодильник, 3x4
//   B  двухъярусная кровать, 5x4
//   A  машина Филиппа: красный минивэн на домкрате, 10x4 (крыша, ниже лобовое и капот)
//   V  телевизор на тумбе, 5x4
//   S  плита с кастрюлей, 4x3
//   H  вешалка с куртками, 3x4
//   U  обувь, 2x1
//   Y  игрушки: кубики и мяч, 3x2
//   O  колесо (лежит), 2x1
//   X  ящик с инструментами, 3x2
//   Q  качели, 5x4 — твёрдая только перекладина, под ней можно пройти; сиденье бьёт
//   Z  песочница, 6x1
//   D  (диван) и e (шезлонг) — на них можно лечь
//   M  стиральная машина, 3x3
//   K  корзина с бельём, 2x2
//   G  швабры с вёдрами, 3x4
//   J  полка с банками закаток, 3x4
//   I  лестница наверх, 12x8: 8 ступенек, на каждую запрыгивают как на платформу
//   R  телевизор с приставкой, 5x4
// Строчные буквы — тоже предметы (заглавных не хватило):
//   d  кукольный домик, 4x4
//   c  стульчики, 3x2
//   h  сарай, 8x6 (на крышу можно залезть с досок)
//   j  БАТУТ, 4x2 — приземлился сверху, и тебя подбрасывает на 8 плиток вверх («БОЙНГ»)
//   p  мешки цемента, 3x2
//   r  бетономешалка, 4x3
//   q  доски, 4x2
//   f  мангал с дымком, 3x2 — верх горячий!
//   z  высокий забор, 1x9 (перелететь можно только с батута)
//   e  шезлонг, 5x2 — на нём можно лечь, как на диване
//   y  кофемашина, 2x2 — твёрдая, рядом ставят кофе u
//
// Предметы высотой до 2 плиток Филипп перепрыгивает с места.
// Выше (3–4 плитки) — только с разбега или с другого предмета. 5 и выше — только со ступеньки.
//
// Предметы и N E L ставятся ОДНИМ символом в ЛЕВЫЙ НИЖНИЙ угол предмета.
// Остальные клетки под предметом оставь точками — игра сама дорисует предмет вверх и вправо.
//
// ПИВО И БУСТЕРЫ (подбираются на бегу):
//   b  кружка пива: +1 кружка (максимум 5) и «подпитие» на 8 с — Филиппа слегка качает,
//      тормозит с запозданием, прыгает выше. Второе пиво подряд — сильнее и дольше
//   x  сигареты: +40% куража, за Филиппом тянется дымок
//   u  кофе: 6 с быстрее и неуязвим (сквозь врагов и ловушки), потом 2 с «отходняк» — медленнее
//   Ставь их и в труднодоступные места как награду, а кофе — перед трудными участками.
//
// КУРАЖ сам убывает примерно за 2 минуты. Чем меньше — тем медленнее бег и ниже прыжок (до 70%).
// Постоять 1 секунду на диване D или шезлонге e — Филипп ляжет и быстро восстановит кураж.
//
// ВРАГИ (ставятся на плитку прямо над полом или над предметом):
//   k  Кирилл: ходит туда-сюда, увидел папу — бежит «КУПИ ИГРУ!». Касание — минус кружка.
//      Запрыгнул сверху — «НУ ПА-А-АП!», сидит 3 секунды и не мешает
//   t  кошка Туся: гуляет, умывается, бросается под ноги. Филипп спотыкается и лежит 1,2 с
//      («МЯУ!»), кружку не отнимает. Если стоит на крыше — спрыгивает вниз
//   w  пылесос: катается туда-сюда. Сбоку — оглушает на 1 с. Сверху можно встать и прокатиться
//
// ЛОВУШКИ:
//   l  лего на полу, 1 плитка: наступил — «АЙ!», минус кружка. Перепрыгивается
//   i  грабли в траве, 1 плитка: наступил — «БАМ!» по лбу, минус кружка, звёздочки
//   o  горшок с лужей, 4x2: на луже (3 плитки слева) Филипп скользит и не может остановиться
//   f  мангал (см. предметы): верх горячий — «ГОРЯЧО!», минус кружка
//   Q  качели (см. предметы): сиденье раскачивается и отбрасывает Филиппа назад
//
// АРЕНА БОССА (блок boss в конце файла):
//   v  Вася, n  Настя — близнецы-босс, ровно по одной на арене
//   a  низкая скамейка, 4x2
//
// ПРАВИЛО: не клади лего и грабли туда, где нужен разбег перед высоким предметом,
// и в узкую щель между предметами — иначе получится ловушка, из которой не выбраться без удара.
//
// СКОРО (буквы уже зарезервированы, пока ничего не делают):
//   m — мама, g — бабушка, s — Саня
//
