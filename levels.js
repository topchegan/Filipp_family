//   второй этаж: bedroom — спальня, corridor — коридор, kirillRoom — комната Кирилла,
//                twinsRoom — комната Васи и Насти, windowEnd — конец коридора с окном
//   двор:        yardHouse — у дома, yardSwing — качели, yardTrampoline — батут, extension и
