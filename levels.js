// =============================================
// КАРТЫ УРОВНЕЙ
// =============================================
//
// Мир состоит из плиток 8x8 пикселей. Один экран — 30 плиток в ширину и 15 в высоту
// (ещё 2 ряда сверху занимает HUD).
//
// Уровень делится на ЧАСТИ (parts). Каждая часть — свой список ЭКРАНОВ (screens),
// они идут друг за другом слева направо. Между частями — затемнение и титр с названием части.
// Шкала HUD, Лера и часы считают весь уровень целиком, через все части.
//
// Каждая часть:
//   name      — название (для титра «ЧАСТЬ 2. ВТОРОЙ ЭТАЖ»)
//   exitScene — (не обязательно) сценка из scenes.js при выходе из части
//   screens   — список экранов
//
// Каждый экран:
//   bg  — фон экрана (обои, окна и мелкие вещи; от него же зависит вид плиток #)
//   map — ровно 15 строк, в каждой ровно 30 символов
//
// Подробная инструкция для правки на iPad — в docs/levels.md.
//
// ЛЕГЕНДА — ИЗ ДВУХ УРОВНЕЙ
//
// 1) ОБЩИЕ символы — одинаковые во ВСЕХ уровнях. Эти буквы нельзя занимать в легенде уровня.
//   .  пусто
//   #  твёрдая плитка (пол, стена). Как она выглядит — зависит от фона экрана
//   -  полка: на неё можно запрыгнуть снизу насквозь, а стоять сверху
//   P  старт части (ровно один в КАЖДОЙ части и на арене)
//   C  телефон-звонок: коснулся — отмазка Лере, Лера отлетает назад, «ЕЩЁ РАЗ» — отсюда
//   N  выход в следующую часть, 3x4 (ровно один в каждой части, кроме последней)
//   E  калитка «ВЫХОД», 4x4 — финиш: ведёт на арену босса (ровно одна, только в последней части).
//      На уровне 2 это арка выхода со двора (рисуется, если фон экрана — archYard), за ней — мама
//   b  пиво: +1 кружка (максимум 5) и «подпитие» на 8 с
//   x  сигареты: +40% куража, за Филиппом тянется дымок
//   u  кофе: 6 с быстрее и неуязвим, потом 2 с «отходняк»
//
// 2) СВОИ символы у каждого уровня — в поле legend внутри уровня (смотри ниже, у уровня 1).
//    Буква → что это: имя предмета (sofa, table...) или особая вещь
//    (kirill, cat, vacuum, vasya, nastya, lego, rake, lera — уровень 1;
//     neighbor, dog, biker, scooter, sprinkler, gossip2, gossip3, keybox — уровень 2;
//     smoker, chatter, coffeeguy, intern, chair, forklift, pipes — уровень 3;
//     junkie, strayDog, steamVent, drunk, teenA, teenB — уровень 4).
//    У уровня 2 могут быть те же буквы, но значить другое — у него будет своя legend.
//
// Предметы и N E ставятся ОДНИМ символом в ЛЕВЫЙ НИЖНИЙ угол предмета.
// Остальные клетки под предметом оставь точками — игра сама дорисует предмет вверх и вправо.
//
// КУРАЖ сам убывает примерно за 2 минуты. Чем меньше — тем медленнее бег и ниже прыжок (до 70%).
// Постоять 1 секунду на диване или шезлонге — Филипп ляжет и быстро восстановит кураж.
//
// ПРАВИЛА, чтобы уровень был проходим при ЛЮБОМ кураже:
// - Обязательный путь — препятствия не выше 3 плиток. Перед предметом в 4 плитки ставь
//   ступеньку высотой 2 плитки вплотную (корзину, ящик, кофемашину, доски).
// - Высокие предметы без ступенек — только «короткий путь» или место для наград.
// - Не клади лего и грабли туда, где нужен разбег, и в узкую щель между предметами.

