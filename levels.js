// Мир состоит из плиток 8x8 пикселей. Один экран — 30 плиток в ширину и 15 в высоту
// (ещё 2 ряда сверху занимает HUD). Уровень — это список ЭКРАНОВ, они идут
// друг за другом слева направо.
//
// Каждый экран:
//   bg  — фон экрана (обои, окна и мелкие вещи; от него же зависит вид плиток #)
//   map — ровно 15 строк, в каждой ровно 30 символов
//
// Подробная инструкция для правки на iPad — в docs/levels.md.
//
// ЛЕГЕНДА СИМВОЛОВ:
//   .  пусто
//   #  твёрдая плитка (пол, стена). Как она выглядит — зависит от фона экрана
//   -  тонкая платформа: на неё можно запрыгнуть снизу, а стоять сверху (полка, подоконник)
//   D  диван, 5x2 плитки (на нём можно стоять)
//   T  стол, 4x2 (стоять на столешнице; под столом можно пройти)
//   W  шкаф, 4x4 (твёрдый, на крышу можно запрыгнуть)
//   F  холодильник, 3x4 (твёрдый)
//   B  двухъярусная кровать, 5x4 (стоять можно на нижней и на верхней полке)
//   A  машина Филиппа: красный минивэн на домкрате, 8x3 (на крышу и капот можно запрыгнуть)
//   P  старт Филиппа (ровно один на уровень)
//   C  чекпоинт — дверной проём с ковриком, 3x4
//   E  финиш — калитка «ВЫХОД», 4x4 (ровно один на уровень)
//
// Крупные вещи (D T W F B A C E) ставятся ОДНИМ символом в ЛЕВЫЙ НИЖНИЙ угол предмета.
// Остальные клетки под предметом оставь точками — игра сама дорисует предмет вверх и вправо.
//
// СКОРО (буквы уже зарезервированы, пока ничего не делают):
//   k — Кирилл, v — Вася, n — Настя, t — кошка Туся,
